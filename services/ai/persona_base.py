MAX_STYLES_IN_PROMPT = 12


def get_coach_archive_text() -> str:
    """Былые заслуги тренеров. Не источник истины по текущему сезону и дивизионам."""
    return COACH_ARCHIVE_TEXT


def get_participant_styles_text(*texts: str, limit: int = MAX_STYLES_IN_PROMPT) -> str:
    """Styles of the participants whose handle occurs in any of `texts`, in order of appearance.

    The whole list is ~60 people, and the model only ever talks to one of them, so
    sending everyone's style was pure prompt weight. Handles are matched as whole
    words, case-insensitively, with or without a leading @.
    """
    haystack = "\n".join(t for t in texts if t)
    found = []
    for handle, style in PARTICIPANT_STYLES.items():
        m = re.search(rf"(?<![A-Za-z0-9_]){re.escape(handle)}(?![A-Za-z0-9_])", haystack, re.IGNORECASE)
        if m:
            found.append((m.start(), handle, style))
    found.sort()
    return "\n".join(f"- @{h} — {s}" for _, h, s in found[:limit])
